/**
 * const,let等の変数宣言
 */
var val1 = 'var変数';
console.log(val1);

// var変数は上書き可能
val1 = 'var変数を上書き';
console.log(val1);

//　var変数は再宣言可能
var val1 = 'var変数を再宣言';
console.log(val1);

let let1 = 'let変数';
console.log(let1);

// let変数は上書き可能
let1 = 'let変数を上書き';
console.log(let1);

